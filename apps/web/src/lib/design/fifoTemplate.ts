import type { FifoConfig, ResetStyle } from "../domain/fifo";

export const TEMPLATE_ID = "sync_fifo@1.0.0";

/** Known defects that can be injected on purpose to demonstrate failure handling. */
export const DEMO_DEFECTS = {
  full_off_by_one: {
    label: "Full flag asserts one entry early",
    find: "assign full    = (count_q == DEPTH_C);",
    replace: "assign full    = (count_q == DEPTH_C - 1);",
  },
} as const;
export type DemoDefect = keyof typeof DEMO_DEFECTS;

interface ResetForms {
  port: string;
  describe: string;
  sensitivity: string;
  active: string;
  inactive: string;
}

export function resetForms(style: ResetStyle): ResetForms {
  switch (style) {
    case "sync_active_low":
      return { port: "rst_n", describe: "synchronous active-low reset (rst_n)", sensitivity: "posedge clk", active: "!rst_n", inactive: "rst_n" };
    case "sync_active_high":
      return { port: "rst", describe: "synchronous active-high reset (rst)", sensitivity: "posedge clk", active: "rst", inactive: "!rst" };
    case "async_active_low":
      return { port: "rst_n", describe: "asynchronous active-low reset (rst_n)", sensitivity: "posedge clk or negedge rst_n", active: "!rst_n", inactive: "rst_n" };
  }
}

export function generateRtl(cfg: FifoConfig, defects: DemoDefect[] = []): string {
  const r = resetForms(cfg.RESET);
  const writeRule = cfg.ALLOW_WRITE_WHEN_FULL_WITH_READ
    ? `//   * A write is accepted when wr_en == 1 and the FIFO is not full, or when it
//     is full and a read is accepted in the same cycle.`
    : `//   * A write is accepted when wr_en == 1 and the FIFO is not full, even if a
//     read is accepted in the same cycle.`;
  let rtl = `// sync_fifo.sv
// Generated by Auto-VLSI from template ${TEMPLATE_ID}.
// Do not edit by hand: every change must become a new, hashed source revision.
//
// Behaviour contract (see design_spec.yaml for the approved requirement IDs):
//   * Single clock domain, ${r.describe}.
//   * First-word-fall-through read port: rd_data shows the oldest stored item
//     whenever empty == 0. rd_data has no defined value while empty == 1.
${writeRule}
//   * A read is accepted when rd_en == 1 and the FIFO is not empty.
//   * Writes while full (without a read) and reads while empty are ignored.
module sync_fifo #(
  parameter WIDTH = ${cfg.WIDTH},
  parameter DEPTH = ${cfg.DEPTH}
) (
  input  wire                       clk,
  input  wire                       ${r.port},
  input  wire                       wr_en,
  input  wire [WIDTH-1:0]           wr_data,
  output wire                       full,
  input  wire                       rd_en,
  output wire [WIDTH-1:0]           rd_data,
  output wire                       empty,
  output wire [$clog2(DEPTH+1)-1:0] count
);

  localparam AW = $clog2(DEPTH);
  localparam CW = $clog2(DEPTH + 1);
  localparam [CW-1:0] DEPTH_C = DEPTH[CW-1:0];
  localparam ALLOW_WRITE_WHEN_FULL_WITH_READ = 1'b${cfg.ALLOW_WRITE_WHEN_FULL_WITH_READ ? 1 : 0};

  reg [WIDTH-1:0] mem [0:DEPTH-1];
  reg [AW-1:0]    wr_ptr;
  reg [AW-1:0]    rd_ptr;
  reg [CW-1:0]    count_q;

  wire do_read  = rd_en && !empty;
  wire do_write = wr_en && (!full || (ALLOW_WRITE_WHEN_FULL_WITH_READ && do_read));

  always @(${r.sensitivity}) begin
    if (${r.active}) begin
      wr_ptr  <= {AW{1'b0}};
      rd_ptr  <= {AW{1'b0}};
      count_q <= {CW{1'b0}};
    end else begin
      if (do_write) wr_ptr <= wr_ptr + 1'b1;
      if (do_read)  rd_ptr <= rd_ptr + 1'b1;
      if (do_write && !do_read)      count_q <= count_q + 1'b1;
      else if (do_read && !do_write) count_q <= count_q - 1'b1;
    end
  end

  // Storage is intentionally not reset; only occupied entries are observable.
  always @(posedge clk) begin
    if (do_write) mem[wr_ptr] <= wr_data;
  end

  assign rd_data = mem[rd_ptr];
  assign full    = (count_q == DEPTH_C);
  assign empty   = (count_q == {CW{1'b0}});
  assign count   = count_q;

\`ifdef FORMAL
  \`include "sync_fifo_props.svh"
\`endif

endmodule
`;
  for (const d of defects) {
    const defect = DEMO_DEFECTS[d];
    if (!rtl.includes(defect.find)) throw new Error(`defect ${d} does not apply to this template`);
    rtl = rtl.replace(defect.find, defect.replace);
  }
  return rtl;
}

export function generateProps(cfg: FifoConfig): string {
  const r = resetForms(cfg.RESET);
  return `// sync_fifo_props.svh
// Formal properties for sync_fifo, included only when FORMAL is defined.
// The abstract model below is derived from the interface contract, not from
// the implementation, so an implementation defect shows up as a counterexample.

  reg f_past_valid = 1'b0;
  always @(posedge clk) f_past_valid <= 1'b1;

  // Start every trace in reset.
  always @(*) if (!f_past_valid) assume (${r.active});

  // Contract-level acceptance rules (REQ-FUNC-003, REQ-FUNC-004, REQ-FUNC-005).
  wire f_rd_acc = rd_en && (f_count != 0);
  wire f_wr_acc = wr_en && ((f_count != DEPTH) || (ALLOW_WRITE_WHEN_FULL_WITH_READ && f_rd_acc));

  reg [CW-1:0] f_count;
  always @(posedge clk) begin
    if (${r.active})                     f_count <= {CW{1'b0}};
    else if (f_wr_acc && !f_rd_acc) f_count <= f_count + 1'b1;
    else if (f_rd_acc && !f_wr_acc) f_count <= f_count - 1'b1;
  end

  // Occupancy and flags (REQ-FUNC-002, REQ-FUNC-003, REQ-FUNC-004).
  always @(*) if (f_past_valid && ${r.inactive}) begin
    assert (f_count <= DEPTH);
    assert (count == f_count);
    assert (full  == (f_count == DEPTH));
    assert (empty == (f_count == 0));
  end

  // Reset establishes the documented initial state (REQ-RST-001).
  always @(posedge clk) if (f_past_valid && $past(${r.active})) begin
    assert (empty);
    assert (!full);
    assert (count == 0);
  end

  // Data integrity and ordering (REQ-FUNC-001): track one arbitrary accepted
  // item and check it is read back unchanged after every older item.
  (* anyseq *) wire f_pick;
  reg              f_tracking;
  reg [WIDTH-1:0]  f_value;
  reg [CW-1:0]     f_ahead;   // items that must leave before the tracked item

  always @(posedge clk) begin
    if (${r.active}) begin
      f_tracking <= 1'b0;
    end else if (!f_tracking && f_pick && f_wr_acc) begin
      f_tracking <= 1'b1;
      f_value    <= wr_data;
      f_ahead    <= f_count - (f_rd_acc ? 1'b1 : 1'b0);
    end else if (f_tracking && f_rd_acc) begin
      if (f_ahead == 0) f_tracking <= 1'b0;
      else              f_ahead    <= f_ahead - 1'b1;
    end
  end

  always @(*) if (f_past_valid && ${r.inactive} && f_tracking) begin
    assert (f_ahead < f_count);
    if (f_ahead == 0) assert (rd_data == f_value);
  end

  // Implementation invariants that make the k-induction proof succeed.
  always @(*) if (f_past_valid && ${r.inactive}) begin
    assert (count_q[AW-1:0] == wr_ptr - rd_ptr);
    if (f_tracking) assert (mem[rd_ptr + f_ahead[AW-1:0]] == f_value);
  end

  // Reachability: make sure the properties above are not vacuous.
${cfg.DEPTH <= 16 ? `  always @(*) if (f_past_valid && ${r.inactive}) cover (full);` : `  // DEPTH > 16: reaching full needs more BMC steps than the time budget allows, so the
  // cover targets 16 stored items; full-flag reachability is exercised by simulation.
  always @(*) if (f_past_valid && ${r.inactive}) cover (count == 16);`}
  always @(posedge clk) if (f_past_valid && ${r.inactive} && $past(f_tracking) && !f_tracking) cover (1'b1);
`;
}

export function generateFilelist(): string {
  return "rtl/sync_fifo.sv\n";
}

/** Draft SDC. It is a proposal until a human approves it; physical runs refuse unapproved constraints. */
export function generateSdc(clockMhz: number): string {
  const period = (1000 / clockMhz).toFixed(3);
  return `# constraints/approved.sdc (DRAFT until approved in the Physical Design Center)
# Generated by Auto-VLSI from the approved clock requirement REQ-CLK-001.
# The 20% I/O delay budget and 0.1 ns uncertainty are PROPOSALS, not user-provided values.
# Reset is timed like any other input (no false path), so reset paths are checked too.
current_design sync_fifo
set clk_name      clk
set clk_port_name clk
set clk_period    ${period}
set clk_io_pct    0.2

set clk_port [get_ports $clk_port_name]
create_clock -name $clk_name -period $clk_period $clk_port
set_clock_uncertainty 0.100 [get_clocks $clk_name]

set non_clock_inputs [lsearch -inline -all -not -exact [all_inputs] $clk_port]
set_input_delay  [expr $clk_period * $clk_io_pct] -clock $clk_name $non_clock_inputs
set_output_delay [expr $clk_period * $clk_io_pct] -clock $clk_name [all_outputs]
`;
}
