/**
 * Embeds the checked-in cocotb regression into the web bundle so the serverless
 * deployment ships exactly the bytes the worker tests run. `--check` fails if stale.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(__dirname, "../../..");
const out = path.resolve(__dirname, "../src/generated/designAssets.ts");
const cocotb = readFileSync(path.join(root, "designs/sync_fifo/verification/cocotb/test_sync_fifo.py"), "utf8");
const body = `// GENERATED by scripts/sync-design-assets.ts from designs/sync_fifo. Do not edit.
export const COCOTB_TEST_PATH = "verification/cocotb/test_sync_fifo.py";
export const COCOTB_TEST_SOURCE = ${JSON.stringify(cocotb)};
`;
if (process.argv.includes("--check")) {
  const current = readFileSync(out, "utf8");
  if (current !== body) {
    console.error("src/generated/designAssets.ts is stale; run `npm run assets:sync`");
    process.exit(1);
  }
  console.log("design assets up to date");
} else {
  writeFileSync(out, body);
  console.log(`wrote ${path.relative(process.cwd(), out)}`);
}
